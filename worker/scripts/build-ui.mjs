// Bundles the Mycelium plugin into the Worker, so /ui/ can serve Stremio's own
// web app with the plugin built in. Run automatically by setup.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const here = fileURLToPath(new URL(".", import.meta.url));
const src = readFileSync(here + "../../enhanced/mycelium.plugin.js", "utf8");
writeFileSync(here + "../src/uiplugin.js", "// Generated by scripts/build-ui.mjs from enhanced/mycelium.plugin.js. Do not edit.\nexport default " + JSON.stringify(src) + ";\n");
console.log("bundled the Mycelium plugin (" + src.length + " bytes) into src/uiplugin.js");
